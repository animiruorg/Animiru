            source,
            url,
            artist,
            author,
            description,
            genre,
            title,
            status,
            thumbnailUrl,
            lastUpdate,
            nextUpdate,
            initialized,
            viewerFlags,
            episodeFlags,
            coverLastModified,
            updateStrategy,
            calculateInterval,
            notes,
            // AY -->
            fetchType,
            parentId,
            seasonFlags,
            seasonNumber,
            seasonSourceOrder,
            backgroundUrl,
            backgroundLastModified,
            // <-- AY
            memo,
            favoriteAt,
        ),
        categories = categories.split(",").map { it.toLong() },
        totalCount = totalCount,
        seenCount = seenCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        // AY -->
        fillermarkCount = fillermarkCount.toLong(),
        // <-- AY
        latestUpload = latestUpload,
        episodeFetchedAt = episodeFetchedAt,
